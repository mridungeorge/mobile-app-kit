#!/usr/bin/env bash
# Native iOS (Swift + SwiftUI, Xcode) production scaffold.
# Generates a buildable XcodeGen SwiftUI project + .mobile state, design tokens, privacy/release docs,
# and Fastlane/CI starters.
#
# Usage:
#   ./new-ios-app.sh <app-name> [bundle-id]
#   ./new-ios-app.sh "Night Notes" com.example.nightnotes
set -euo pipefail

APP_NAME="${1:-}"
BUNDLE_ID="${2:-}"
if [[ -z "$APP_NAME" ]]; then
  echo "Usage: $0 <app-name> [bundle-id]" >&2
  echo "Example: $0 \"Night Notes\" com.example.nightnotes" >&2
  exit 1
fi

SKILL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ROOT="$(pwd)"
TARGET="$ROOT/$APP_NAME"

if [[ -d "$TARGET" ]]; then
  echo "Directory $TARGET already exists — refusing to overwrite." >&2
  exit 1
fi

mkdir -p "$TARGET/.mobile/metadata" "$TARGET/.mobile/screenshots" "$TARGET/docs" "$TARGET/ci" "$TARGET/fastlane"

cp "$SKILL_DIR/assets/design-tokens.json" "$TARGET/docs/design-tokens.json" 2>/dev/null || true
cp "$SKILL_DIR/assets/ios/PrivacyInfo.xcprivacy" "$TARGET/docs/PrivacyInfo.xcprivacy" 2>/dev/null || true
cp "$SKILL_DIR/references/native-ios-release.md" "$TARGET/docs/native-ios-release.md" 2>/dev/null || true
cp "$SKILL_DIR/references/mobile-testing.md" "$TARGET/docs/mobile-testing.md" 2>/dev/null || true
cp "$SKILL_DIR/references/ios-app-store.md" "$TARGET/docs/ios-app-store.md" 2>/dev/null || true
cp "$SKILL_DIR/assets/ci/ios-release.yml" "$TARGET/ci/ios-release.yml" 2>/dev/null || true
cp "$SKILL_DIR/assets/ios/Fastfile" "$TARGET/fastlane/Fastfile" 2>/dev/null || true
cp "$SKILL_DIR/assets/ios/Appfile.example" "$TARGET/fastlane/Appfile.example" 2>/dev/null || true

# Buildable native project (SwiftUI + XcodeGen project.yml)
SCAFFOLD_ARGS=(--platform ios --name "$APP_NAME" --out "$TARGET/ios")
if [[ -n "$BUNDLE_ID" ]]; then SCAFFOLD_ARGS+=(--bundle-id "$BUNDLE_ID"); fi
node "$SKILL_DIR/scripts/scaffold-native.mjs" "${SCAFFOLD_ARGS[@]}"

cat > "$TARGET/.gitignore" <<'EOF'
# Xcode
*.xcodeproj/
*.xcworkspace/
xcuserdata/
DerivedData/
build/
*.ipa
*.dSYM.zip

# Signing material
*.p12
*.mobileprovision
*.p8
fastlane/report.xml
fastlane/screenshots/

# Local factory state
.mobile/
EOF

cat > "$TARGET/.mobile/STATE.md" <<EOF
# State
stage: INTAKE
app: $APP_NAME
stack: native-ios (Swift + SwiftUI, Xcode)
project: ios/
updated: $(date -u +"%Y-%m-%dT%H:%M:%SZ")
next: questionnaire -> route-idea -> preview approval -> product-architect -> design -> build
EOF

cat > "$TARGET/README.md" <<'EOF'
# __APP_NAME__ (placeholder — rename me)

Generated by **Mobile App Factory**.

| Path | What it is |
|---|---|
| `ios/` | Buildable SwiftUI project source + XcodeGen `project.yml` |
| `docs/` | Design tokens, release checklist, testing guide, iOS/store guides, PrivacyInfo |
| `fastlane/` | Fastfile + Appfile example |
| `ci/ios-release.yml` | CI starter for macOS runners |
| `.mobile/` | Factory state and pipeline artifacts |

## Run it (macOS)

```bash
cd ios
brew install xcodegen
xcodegen generate
open *.xcodeproj
```

Select a simulator and press Run. Set Team/signing in Xcode for device builds and Archive.

## Continue the factory pipeline

```bash
node <skill-dir>/scripts/questionnaire.mjs --out .mobile
node <skill-dir>/scripts/generate-preview.mjs --dir .mobile
node <skill-dir>/scripts/review-preview.mjs --dir .mobile --approve
```

Then build the real screens from `.mobile/01-prd.md` and `.mobile/02-design.md`.
EOF

if command -v sed >/dev/null 2>&1; then
  sed -i.bak "s/__APP_NAME__/$APP_NAME/g" "$TARGET/README.md" 2>/dev/null || true
  rm -f "$TARGET/README.md.bak"
fi

cat <<EOF

Native iOS project prepared at: $TARGET

Included:
  - ios/      buildable SwiftUI sources, XcodeGen project.yml, PrivacyInfo, Assets, XCTest
  - .mobile/  factory state
  - docs/     design tokens, iOS release/store guides, testing, PrivacyInfo
  - fastlane/ (Fastfile, Appfile.example)
  - ci/ios-release.yml

Next:
  1. On macOS: brew install xcodegen && cd "$TARGET/ios" && xcodegen generate
  2. Open the generated .xcodeproj, set Team/signing, press Run
  3. Run the factory pipeline from "$TARGET": questionnaire -> preview approval -> PRD/design/build

EOF
