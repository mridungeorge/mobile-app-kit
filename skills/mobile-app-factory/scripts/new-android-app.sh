#!/usr/bin/env bash
# Native Android (Kotlin + Jetpack Compose, Android Studio) production scaffold.
# Generates a buildable Gradle project + .mobile state, design tokens, release docs/templates, and CI starters.
#
# Usage:
#   ./new-android-app.sh <app-name> [applicationId]
#   ./new-android-app.sh "Night Notes" com.example.nightnotes
set -euo pipefail

APP_NAME="${1:-}"
PACKAGE="${2:-}"
if [[ -z "$APP_NAME" ]]; then
  echo "Usage: $0 <app-name> [applicationId]" >&2
  echo "Example: $0 \"Night Notes\" com.example.nightnotes" >&2
  exit 1
fi

SKILL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ROOT="$(pwd)"
TARGET="$ROOT/$APP_NAME"

if [[ -d "$TARGET" ]]; then
  echo "Directory $TARGET already exists — refusing to overwrite." >&2
  exit 1
fi

mkdir -p "$TARGET/.mobile/metadata" "$TARGET/.mobile/screenshots" "$TARGET/docs" "$TARGET/ci" "$TARGET/android-templates"

# Core artifacts
cp "$SKILL_DIR/assets/design-tokens.json" "$TARGET/docs/design-tokens.json" 2>/dev/null || true
cp "$SKILL_DIR/assets/android/data-safety-worksheet.md" "$TARGET/docs/data-safety-worksheet.md" 2>/dev/null || true
cp "$SKILL_DIR/references/native-android-release.md" "$TARGET/docs/native-android-release.md" 2>/dev/null || true
cp "$SKILL_DIR/references/mobile-testing.md" "$TARGET/docs/mobile-testing.md" 2>/dev/null || true
cp "$SKILL_DIR/assets/ci/android-release.yml" "$TARGET/ci/android-release.yml" 2>/dev/null || true

# Android production templates/snippets
cp "$SKILL_DIR/assets/android/README-gradle-starter.md" "$TARGET/android-templates/README-gradle-starter.md" 2>/dev/null || true
cp "$SKILL_DIR/assets/android/signing-and-build.gradle.kts.snippet" "$TARGET/android-templates/signing-and-build.gradle.kts.snippet" 2>/dev/null || true
cp "$SKILL_DIR/assets/android/proguard-rules.pro" "$TARGET/android-templates/proguard-rules.pro" 2>/dev/null || true
cp "$SKILL_DIR/assets/android/keystore.properties.example" "$TARGET/android-templates/keystore.properties.example" 2>/dev/null || true

# Buildable native project (Kotlin + Compose + Gradle version catalog)
SCAFFOLD_ARGS=(--platform android --name "$APP_NAME" --out "$TARGET/android")
if [[ -n "$PACKAGE" ]]; then SCAFFOLD_ARGS+=(--package "$PACKAGE"); fi
node "$SKILL_DIR/scripts/scaffold-native.mjs" "${SCAFFOLD_ARGS[@]}"

cat > "$TARGET/.gitignore" <<'EOF'
# Android / Gradle
*.jks
*.keystore
keystore.properties
local.properties
.gradle/
build/
captures/
.cxx/
*.iml
.idea/

# Local factory state
.mobile/
EOF

cat > "$TARGET/.mobile/STATE.md" <<EOF
# State
stage: INTAKE
app: $APP_NAME
stack: native-android (Kotlin + Jetpack Compose, Android Studio, Gradle)
project: android/
updated: $(date -u +"%Y-%m-%dT%H:%M:%SZ")
next: questionnaire -> route-idea -> preview approval -> product-architect -> design -> build
EOF

cat > "$TARGET/README.md" <<'EOF'
# __APP_NAME__ (placeholder — rename me)

Generated by **Mobile App Factory**.

| Path | What it is |
|---|---|
| `android/` | Buildable Kotlin + Jetpack Compose project (Gradle, version catalog) |
| `docs/` | Design tokens, release checklist, testing guide, data-safety worksheet |
| `android-templates/` | Signing/build snippet, ProGuard rules, keystore example |
| `ci/android-release.yml` | CI starter: lint, test, signed AAB |
| `.mobile/` | Factory state and pipeline artifacts |

## Run it

```bash
cd android
./gradlew :app:assembleDebug   # Gradle wrapper included; only a JDK 17 is required
```

Or open `android/` in **Android Studio** and press Run.

## Continue the factory pipeline

```bash
node <skill-dir>/scripts/questionnaire.mjs --out .mobile
node <skill-dir>/scripts/generate-preview.mjs --dir .mobile
node <skill-dir>/scripts/review-preview.mjs --dir .mobile --approve
```

Then build the real screens from `.mobile/01-prd.md` and `.mobile/02-design.md`.
EOF

# Substitute the display name placeholder in the generated README only.
if command -v sed >/dev/null 2>&1; then
  sed -i.bak "s/__APP_NAME__/$APP_NAME/g" "$TARGET/README.md" 2>/dev/null || true
  rm -f "$TARGET/README.md.bak"
fi

cat <<EOF

Native Android project prepared at: $TARGET

Included:
  - android/  buildable Kotlin + Compose project (settings, version catalog, app module, theme, HomeScreen, tests)
  - .mobile/  factory state
  - docs/     design tokens, release checklist, testing, data-safety worksheet
  - android-templates/ (Gradle signing/build snippet, proguard, keystore example)
  - ci/android-release.yml

Next:
  1. cd "$TARGET/android" && ./gradlew :app:assembleDebug   (wrapper included)
  2. Open android/ in Android Studio (or run the command above)
  3. Run the factory pipeline from "$TARGET": questionnaire -> preview approval -> PRD/design/build

EOF
